CREATE TABLE public.council_members (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	council_id BIGINT NOT NULL REFERENCES public.councils(id) ON DELETE CASCADE,
	user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
	role TEXT NOT NULL DEFAULT 'registration_manager'
		CHECK (role IN ('owner', 'admin', 'registration_manager', 'viewer')),
	created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
	UNIQUE (council_id, user_id)
);

CREATE TABLE public.council_invitations (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	council_id BIGINT NOT NULL REFERENCES public.councils(id) ON DELETE CASCADE,
	email TEXT NOT NULL CHECK (length(trim(email)) BETWEEN 3 AND 320),
	role TEXT NOT NULL DEFAULT 'registration_manager'
		CHECK (role IN ('owner', 'admin', 'registration_manager', 'viewer')),
	invited_by UUID REFERENCES auth.users(id) ON DELETE SET NULL,
	accepted_at TIMESTAMPTZ,
	created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
	UNIQUE (council_id, email)
);

CREATE TABLE public.registration_events (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	council_id BIGINT NOT NULL REFERENCES public.councils(id) ON DELETE CASCADE,
	title TEXT NOT NULL CHECK (length(trim(title)) BETWEEN 1 AND 160),
	public_slug TEXT NOT NULL UNIQUE CHECK (length(public_slug) BETWEEN 12 AND 100),
	status TEXT NOT NULL DEFAULT 'draft'
		CHECK (status IN ('draft', 'open', 'closed', 'archived')),
	description TEXT,
	starts_at TIMESTAMPTZ,
	closes_at TIMESTAMPTZ,
	created_by UUID REFERENCES auth.users(id) ON DELETE SET NULL,
	created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
	updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE public.registration_types (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	event_id BIGINT NOT NULL REFERENCES public.registration_events(id) ON DELETE CASCADE,
	name TEXT NOT NULL CHECK (length(trim(name)) BETWEEN 1 AND 100),
	affiliation_prompt TEXT NOT NULL DEFAULT 'Hvem representerer du?'
		CHECK (length(trim(affiliation_prompt)) BETWEEN 1 AND 180),
	display_template TEXT NOT NULL DEFAULT '{tilhorighet}'
		CHECK (length(display_template) BETWEEN 1 AND 180),
	requires_affiliation BOOLEAN NOT NULL DEFAULT true,
	can_receive_delegate_number BOOLEAN NOT NULL DEFAULT true,
	position INTEGER NOT NULL DEFAULT 0,
	created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
	UNIQUE (event_id, name)
);

CREATE TABLE public.registrations (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	event_id BIGINT NOT NULL REFERENCES public.registration_events(id) ON DELETE CASCADE,
	type_id BIGINT NOT NULL REFERENCES public.registration_types(id) ON DELETE RESTRICT,
	full_name TEXT NOT NULL CHECK (length(trim(full_name)) BETWEEN 2 AND 160),
	email TEXT CHECK (email IS NULL OR length(trim(email)) BETWEEN 3 AND 320),
	phone TEXT CHECK (phone IS NULL OR length(trim(phone)) <= 40),
	affiliation TEXT,
	delegate_number INTEGER CHECK (delegate_number IS NULL OR delegate_number > 0),
	status TEXT NOT NULL DEFAULT 'submitted'
		CHECK (status IN ('submitted', 'approved', 'rejected', 'waitlist', 'withdrawn')),
	notes TEXT,
	created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
	updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
	UNIQUE (event_id, delegate_number)
);

CREATE INDEX council_members_user_council_idx
	ON public.council_members (user_id, council_id);
CREATE INDEX council_invitations_email_idx
	ON public.council_invitations (lower(email), accepted_at);
CREATE INDEX registration_events_council_status_idx
	ON public.registration_events (council_id, status, created_at DESC);
CREATE INDEX registration_types_event_position_idx
	ON public.registration_types (event_id, position, id);
CREATE INDEX registrations_event_status_idx
	ON public.registrations (event_id, status, created_at);

