CREATE OR REPLACE FUNCTION public.is_council_member(
	p_council_id BIGINT,
	p_roles TEXT[] DEFAULT NULL
)
RETURNS BOOLEAN
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
	SELECT EXISTS (
		SELECT 1
		FROM public.council_members AS member
		WHERE member.council_id = p_council_id
			AND member.user_id = auth.uid()
			AND (p_roles IS NULL OR member.role = ANY (p_roles))
	);
$$;

CREATE OR REPLACE FUNCTION public.is_event_member(
	p_event_id BIGINT,
	p_roles TEXT[] DEFAULT NULL
)
RETURNS BOOLEAN
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
	SELECT EXISTS (
		SELECT 1
		FROM public.registration_events AS event
		WHERE event.id = p_event_id
			AND public.is_council_member(event.council_id, p_roles)
	);
$$;

CREATE OR REPLACE FUNCTION public.claim_council_invitations()
RETURNS SETOF public.council_members
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
	current_email TEXT;
BEGIN
	SELECT lower(trim(users.email)) INTO current_email
	FROM auth.users AS users
	WHERE users.id = auth.uid();

	IF current_email IS NULL THEN
		RETURN;
	END IF;

	INSERT INTO public.council_members (council_id, user_id, role)
	SELECT invitation.council_id, auth.uid(), invitation.role
	FROM public.council_invitations AS invitation
	WHERE lower(trim(invitation.email)) = current_email
		AND invitation.accepted_at IS NULL
	ON CONFLICT (council_id, user_id)
	DO UPDATE SET role = EXCLUDED.role;

	UPDATE public.council_invitations
	SET accepted_at = now()
	WHERE lower(trim(email)) = current_email
		AND accepted_at IS NULL;

	RETURN QUERY
	SELECT member.*
	FROM public.council_members AS member
	WHERE member.user_id = auth.uid();
END;
$$;

