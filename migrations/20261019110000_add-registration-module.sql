CREATE POLICY "members read council memberships"
	ON public.council_members FOR SELECT TO authenticated
	USING (public.is_council_member(council_id));

CREATE POLICY "owners and admins read invitations"
	ON public.council_invitations FOR SELECT TO authenticated
	USING (public.is_council_member(council_id, ARRAY['owner', 'admin']));

CREATE POLICY "owners and admins create invitations"
	ON public.council_invitations FOR INSERT TO authenticated
	WITH CHECK (
		public.is_council_member(council_id, ARRAY['owner', 'admin'])
		AND invited_by = auth.uid()
	);

CREATE POLICY "owners and admins update invitations"
	ON public.council_invitations FOR UPDATE TO authenticated
	USING (public.is_council_member(council_id, ARRAY['owner', 'admin']))
	WITH CHECK (public.is_council_member(council_id, ARRAY['owner', 'admin']));

