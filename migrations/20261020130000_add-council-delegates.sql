CREATE TABLE public.council_delegates (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  council_id BIGINT NOT NULL REFERENCES public.councils(id) ON DELETE CASCADE,
  delegate_number TEXT NOT NULL CHECK (length(trim(delegate_number)) BETWEEN 1 AND 40),
  full_name TEXT NOT NULL DEFAULT '' CHECK (length(full_name) <= 200),
  organization TEXT NOT NULL DEFAULT '' CHECK (length(organization) <= 240),
  position INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (council_id, delegate_number)
);

CREATE INDEX council_delegates_council_position_idx
  ON public.council_delegates (council_id, position, id);

CREATE TRIGGER council_delegates_updated_at
  BEFORE UPDATE ON public.council_delegates
  FOR EACH ROW EXECUTE FUNCTION system.update_updated_at();

ALTER TABLE public.council_delegates ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.council_delegates FROM anon, authenticated;
REVOKE ALL ON SEQUENCE public.council_delegates_id_seq FROM anon, authenticated;
