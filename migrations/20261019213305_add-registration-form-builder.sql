CREATE TABLE public.registration_form_fields (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	event_id BIGINT NOT NULL REFERENCES public.registration_events(id) ON DELETE CASCADE,
	label TEXT NOT NULL CHECK (length(trim(label)) BETWEEN 1 AND 200),
	field_type TEXT NOT NULL DEFAULT 'short_text'
		CHECK (field_type IN ('short_text', 'long_text', 'single_choice')),
	help_text TEXT CHECK (help_text IS NULL OR length(help_text) <= 500),
	is_required BOOLEAN NOT NULL DEFAULT false,
	position INTEGER NOT NULL DEFAULT 0,
	system_key TEXT CHECK (
		system_key IS NULL OR system_key IN ('full_name', 'email', 'phone', 'participant_type', 'affiliation')
	),
	options TEXT[] NOT NULL DEFAULT '{}',
	created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
	updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
	CHECK (cardinality(options) <= 100)
);

CREATE UNIQUE INDEX registration_form_fields_event_system_key_idx
	ON public.registration_form_fields (event_id, system_key)
	WHERE system_key IS NOT NULL;

CREATE INDEX registration_form_fields_event_position_idx
	ON public.registration_form_fields (event_id, position, id);

CREATE TRIGGER registration_form_fields_updated_at
	BEFORE UPDATE ON public.registration_form_fields
	FOR EACH ROW EXECUTE FUNCTION system.update_updated_at();

CREATE TABLE public.registration_answers (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	event_id BIGINT NOT NULL REFERENCES public.registration_events(id) ON DELETE CASCADE,
	registration_id BIGINT NOT NULL REFERENCES public.registrations(id) ON DELETE CASCADE,
	field_id BIGINT NOT NULL REFERENCES public.registration_form_fields(id) ON DELETE CASCADE,
	value_text TEXT,
	created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
	UNIQUE (registration_id, field_id),
	CHECK (value_text IS NULL OR length(value_text) <= 5000)
);

CREATE INDEX registration_answers_event_registration_idx
	ON public.registration_answers (event_id, registration_id, field_id);

CREATE OR REPLACE FUNCTION public.validate_registration_answer_event()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public, pg_temp
AS $$
BEGIN
	IF NOT EXISTS (
		SELECT 1
		FROM public.registrations AS registration
		JOIN public.registration_form_fields AS field
			ON field.id = NEW.field_id
		WHERE registration.id = NEW.registration_id
			AND registration.event_id = NEW.event_id
			AND field.event_id = NEW.event_id
	) THEN
		RAISE EXCEPTION 'Registration answer must use a field from the same event';
	END IF;
	RETURN NEW;
END;
$$;

CREATE TRIGGER registration_answers_validate_event
	BEFORE INSERT OR UPDATE ON public.registration_answers
	FOR EACH ROW EXECUTE FUNCTION public.validate_registration_answer_event();

INSERT INTO public.registration_form_fields
	(event_id, label, field_type, is_required, position, system_key)
SELECT event.id, defaults.label, defaults.field_type, defaults.is_required, defaults.position, defaults.system_key
FROM public.registration_events AS event
CROSS JOIN (VALUES
	('Fullt navn', 'short_text', true, 0, 'full_name'),
	('E-postadresse', 'short_text', false, 1, 'email'),
	('Telefonnummer', 'short_text', false, 2, 'phone'),
	('Hvordan deltar du?', 'single_choice', true, 3, 'participant_type'),
	('Hvem representerer du?', 'short_text', true, 4, 'affiliation')
) AS defaults(label, field_type, is_required, position, system_key)
ON CONFLICT (event_id, system_key) WHERE system_key IS NOT NULL DO NOTHING;

ALTER TABLE public.registration_form_fields ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.registration_answers ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON public.registration_form_fields FROM anon, authenticated;
REVOKE ALL ON public.registration_answers FROM anon, authenticated;
REVOKE ALL ON FUNCTION public.validate_registration_answer_event() FROM PUBLIC, anon, authenticated;

GRANT SELECT, INSERT, UPDATE, DELETE ON public.registration_form_fields TO authenticated;
GRANT SELECT ON public.registration_answers TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.registration_form_fields_id_seq TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.registration_answers_id_seq TO authenticated;

CREATE POLICY "members read registration form fields"
	ON public.registration_form_fields FOR SELECT TO authenticated
	USING (public.is_event_member(event_id));

CREATE POLICY "managers create registration form fields"
	ON public.registration_form_fields FOR INSERT TO authenticated
	WITH CHECK (public.is_event_member(event_id, ARRAY['owner', 'admin', 'registration_manager']));

CREATE POLICY "managers update registration form fields"
	ON public.registration_form_fields FOR UPDATE TO authenticated
	USING (public.is_event_member(event_id, ARRAY['owner', 'admin', 'registration_manager']))
	WITH CHECK (public.is_event_member(event_id, ARRAY['owner', 'admin', 'registration_manager']));

CREATE POLICY "managers delete registration form fields"
	ON public.registration_form_fields FOR DELETE TO authenticated
	USING (public.is_event_member(event_id, ARRAY['owner', 'admin', 'registration_manager']));

CREATE POLICY "members read registration answers"
	ON public.registration_answers FOR SELECT TO authenticated
	USING (public.is_event_member(event_id));
