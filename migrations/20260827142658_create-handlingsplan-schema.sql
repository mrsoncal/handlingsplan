REVOKE ALL ON public.innspill FROM anon, authenticated;
REVOKE ALL ON SEQUENCE public.councils_id_seq FROM anon, authenticated;
REVOKE ALL ON SEQUENCE public.council_tema_id_seq FROM anon, authenticated;
REVOKE ALL ON SEQUENCE public.innspill_id_seq FROM anon, authenticated;
